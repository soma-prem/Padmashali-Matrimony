export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      return localStorage.getItem(STORAGE_KEY) === 'mr' ? 'mr' : 'en'
    } catch {
      return 'en'
    }
  })

  useEffect(() => {
    document.documentElement.lang = language
    try {
      localStorage.setItem(STORAGE_KEY, language)
    } catch {
      // Language selection remains available for the current session.
    }
  }, [language])

  const toggleLanguage = useCallback(() => {
    setLanguage((current) => current === 'en' ? 'mr' : 'en')
  }, [])

  const t = useCallback((englishText) => {
    if (language === 'en' || typeof englishText !== 'string') return englishText
    return MARATHI_TRANSLATIONS[englishText] ?? englishText
  }, [language])

  const value = useMemo(() => ({ language, setLanguage, toggleLanguage, t }), [
    language,
    toggleLanguage,
    t,
  ])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within a LanguageProvider')
  return context
}
